FONT = 'Arial'
RLM  = '‏'   # Right-to-Left Mark – forces numbers to the right in RTL paragraphs

def _fix_num(text):
    """Add RLM before a leading section number so it renders on the right margin."""
    m = re.match(r'^\+?\s*\.?(\d+(?:\.\d+)*)(\s+)', text)
    if m:
        num    = m.group(1)
        spaces = m.group(2)
        rest   = text[m.end():]
        return RLM + num + spaces + rest
    return text

def rtl(para):
    pPr = para._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    bidi.set(qn('w:val'), '1')
    pPr.append(bidi)

def p(doc, text, bold=False, underline=False, size=11, align='right',
      sb=0, sa=4, indent=0):
    text = _fix_num(text)
    para = doc.add_paragraph()
    rtl(para)
    if align == 'center':
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    else:
        para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pf = para.paragraph_format
    pf.space_before = Pt(sb)
    pf.space_after  = Pt(sa)
    if indent:
        pf.right_indent = Cm(indent * 0.7)
    run = para.add_run(text)
    run.bold = bold
    run.underline = underline
    run.font.size = Pt(size)
    run.font.name = FONT
    return para

def heading(doc, text, sb=8):
    return p(doc, text, bold=True, underline=True, sb=sb, sa=4)

